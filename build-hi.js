// Condition-page metadata lives with its content, so there is one place to edit it.
for (const c of CONDITIONS) {
  META[c.slug] = { title: c.title.hi, desc: c.desc.hi };
}

const enPath = f => (f === 'index.html' ? '/' : `/${f}`);
const hiPath = f => (f === 'index.html' ? '/hi/' : `/hi/${f}`);

function hreflangBlock(file) {
  return [
    '    <!-- Generated by build-hi.js. Do not edit by hand. -->',
    `    <link rel="alternate" hreflang="en-IN" href="${ORIGIN}${enPath(file)}">`,
    `    <link rel="alternate" hreflang="hi-IN" href="${ORIGIN}${hiPath(file)}">`,
    `    <link rel="alternate" hreflang="x-default" href="${ORIGIN}${enPath(file)}">`
  ].join('\n');
}

function setMeta(html, attr, name, value) {
  const re = new RegExp(`(<meta\\s+${attr}="${name}"\\s+content=")[^"]*(")`, 'i');
  return re.test(html) ? html.replace(re, `$1${value}$2`) : html;
}

function toHindiPage(html, file) {
  const m = META[file];

  // The English source already had a generated hreflang block injected above; strip it so the
  // Hindi page gets exactly one, not two.
  html = html.replace(/\n\s*<!-- Generated by build-hi\.js[\s\S]*?hreflang="x-default"[^>]*>/g, '');

  // 1. Language of the document itself.
  html = html.replace(/<html[^>]*>/i, '<html lang="hi" dir="ltr">');
  html = html.replace(/<body class="lang-en"/i, '<body class="lang-hi"');
  html = html.replace(/<meta http-equiv="Content-Language" content="en">/i,
                      '<meta http-equiv="Content-Language" content="hi">');

  // 2. Everything a Hindi searcher sees in the results page.
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${m.title}</title>`);
  html = setMeta(html, 'name', 'description', m.desc);
  html = setMeta(html, 'property', 'og:title', m.title);
  html = setMeta(html, 'property', 'og:description', m.desc);
  html = setMeta(html, 'name', 'twitter:title', m.title);
  html = setMeta(html, 'name', 'twitter:description', m.desc);
  html = setMeta(html, 'property', 'og:locale', 'hi_IN');
  html = setMeta(html, 'property', 'og:locale:alternate', 'en_IN');
  html = setMeta(html, 'property', 'og:url', `${ORIGIN}${hiPath(file)}`);

  // 3. This page is its own canonical -- it is a distinct URL, not a copy of the English one.
  html = html.replace(/<link rel="canonical" href="[^"]*">/i,
                      `<link rel="canonical" href="${ORIGIN}${hiPath(file)}">`);

  // 4. Reciprocal hreflang, inserted right after the canonical.
  html = html.replace(/(<link rel="canonical" href="[^"]*">)/i, `$1\n${hreflangBlock(file)}`);

  // 4b. Condition pages carry JSON-LD baked in English. Copying the HTML as text would
  // leave a Hindi page described by English structured data pointing at the English URL --
  // worse than none, because it is the one signal meant to make the page machine-quotable.
  const cond = CONDITIONS.find(c => c.slug === file);
  if (cond) {
    html = html.replace(
      /<script type="application\/ld\+json">[\s\S]*?<\/script>/,
      `<script type="application/ld+json">\n${conditionSchema(cond, 'hi')}\n    </script>`
    );
  }

  // 5. Relative paths break one directory down, so make asset URLs root-relative.
  html = html.replace(/(src|href)="(assets\/[^"]*)"/g, '$1="/$2"');
  html = html.replace(/(src|href)="(hardcoded_routes\.js[^"]*)"/g, '$1="/$2"');
  html = html.replace(/href="(favicon-\d+x\d+\.png|favicon\.ico|apple-touch-icon\.png|site\.webmanifest[^"]*)"/g,
                      'href="/$1"');

  // 6. Internal navigation stays inside the Hindi site.
  html = html.replace(/href="([a-z-]+\.html)"/g, 'href="/hi/$1"');
  html = html.replace(/href="\/"(\s)/g, 'href="/hi/"$1');
  html = html.replace(/href="\/">/g, 'href="/hi/">');

  return html;
}

// --- English side: the pair only counts if BOTH pages point at each other -------------------
function addHreflangToEnglish(file) {
  const p = path.join(ROOT, file);
  let html = fs.readFileSync(p, 'utf8');
  html = html.replace(/\n\s*<!-- Generated by build-hi\.js[\s\S]*?hreflang="x-default"[^>]*>/g, '');
  if (!/<link rel="canonical"/i.test(html)) {
    console.warn(`  ! ${file} has no canonical tag; skipping hreflang`);
    return false;
  }
  html = html.replace(/(<link rel="canonical" href="[^"]*">)/i, `$1\n${hreflangBlock(file)}`);
  fs.writeFileSync(p, html);
  return true;
}

function buildSitemap() {
  const today = process.env.BUILD_DATE || new Date().toISOString().slice(0, 10);
  const urls = PAGES.flatMap(f => [
    { loc: ORIGIN + enPath(f), en: ORIGIN + enPath(f), hi: ORIGIN + hiPath(f), pri: f === 'index.html' ? '1.0' : '0.8' },
    { loc: ORIGIN + hiPath(f), en: ORIGIN + enPath(f), hi: ORIGIN + hiPath(f), pri: f === 'index.html' ? '1.0' : '0.8' }
  ]);
  const body = urls.map(u => `  <url>
    <loc>${u.loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${u.pri}</priority>
    <xhtml:link rel="alternate" hreflang="en-IN" href="${u.en}"/>
    <xhtml:link rel="alternate" hreflang="hi-IN" href="${u.hi}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${u.en}"/>
  </url>`).join('\n');
  fs.writeFileSync(path.join(ROOT, 'sitemap.xml'),
`<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by build-hi.js. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${body}
</urlset>
`);
  return urls.length;
}

// --- run ------------------------------------------------------------------------------------
fs.mkdirSync(OUT_DIR, { recursive: true });

console.log('Adding hreflang to English pages');
PAGES.forEach(f => { if (addHreflangToEnglish(f)) console.log(`  ${f}`); });

console.log('\nGenerating /hi/');
for (const file of PAGES) {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const out = toHindiPage(src, file);
  fs.writeFileSync(path.join(OUT_DIR, file), out);
  console.log(`  hi/${file.padEnd(20)} title ${META[file].title.length} chars · desc ${META[file].desc.length}`);
}

const n = buildSitemap();
console.log(`\nsitemap.xml rewritten with ${n} URLs (${n / 2} pages x 2 languages, hreflang-annotated)`);
