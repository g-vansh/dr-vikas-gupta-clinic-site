#!/usr/bin/env node
/**
 * Generates the Hindi site at /hi/ from the English pages.
 *
 * Why this exists
 * ---------------
 * Every page already carries both languages in its DOM (.lang-en / .lang-hi spans) and used
 * to switch between them with a CSS class. That meant one URL served both languages, so
 * Google had nowhere to send a Hindi searcher: `/` and `/?lang=hi` returned byte-identical
 * HTML, both declaring <html lang="en">, with no hreflang anywhere.
 *
 * Search Console showed the cost: Hindi queries ranked on page one -- position 1.0 for
 * स्किन रोग विशेषज्ञ, 1.5 for डर्मेटोलॉजिस्ट near me -- and earned almost no clicks, because
 * the snippet shown was in English.
 *
 * So this script does not translate anything. The Hindi is already written. It re-points one
 * copy of each page at a Hindi URL with Hindi metadata, and cross-links the two with hreflang.
 *
 * Run:  npm run build:hi      (and commit the generated /hi/ directory)
 */

const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const OUT_DIR = path.join(ROOT, 'hi');
const ORIGIN = 'https://www.drvikasgupta.skin';

const { CONDITIONS } = require('./conditions.data');
const { schema: conditionSchema } = require('./build-conditions');

const CORE_PAGES = ['index.html', 'about.html', 'services.html', 'testimonials.html', 'appointment.html', 'faq.html'];
// Condition pages are generated by build-conditions.js and get Hindi twins here too, so the
// Hindi site gains a page every time the English one does.
const PAGES = [...CORE_PAGES, ...CONDITIONS.map(c => c.slug)];

// Hindi metadata is written around the words this clinic's searchers actually type, measured
// across both scripts in Search Console (3 months to 10 Aug 2026):
//
//   चर्म रोग / charm rog     36 impressions across 17 queries   <- the leading term
//   स्किन (in Hindi phrasing) 26 / 14
//   डर्मेटोलॉजिस्ट           14 /  5
//   त्वचा रोग / twacha       13 /  8
//
// चर्म रोग and त्वचा रोग are synonyms and both are standard, but चर्म रोग is typed nearly
// three times as often here — so titles lead with it and descriptions carry the alternatives,
// which is how a page covers all four without keyword-stuffing any one of them.
//
// Do NOT reintroduce लेज़र (laser): the clinic lists no such service. See conditions.data.js.
